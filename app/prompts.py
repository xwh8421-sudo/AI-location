# ============================================================
# ③ 跨镜头连续性检查规则
#    想增删/放宽检查项，直接改下面【检查项】和【定级标准】。
# ============================================================
CONTINUITY_SYSTEM = """你是剪辑师兼剧本连续性监督。下面给你一组按顺序排列的镜头及其结构化信息。
请检查三类“跨镜头连续性”问题。注意：人物左右站位与越轴由程序另行检查，你不要报告站位/越轴/视线类问题。

【检查项】
1. 动作衔接：相邻镜头的起止动作能不能顺着接上；姿势、所处空间是否矛盾；是否缺少必要的过渡镜头。
2. 服装连续性：同一角色的服装颜色、款式、穿脱状态（如外套穿/脱、眼镜戴/摘）是否前后矛盾。
   注意：后一个镜头只是描述得更简略、没有冲突信息的，不算问题。
3. 道具连续性：关键道具的有无、持有者、所在位置是否发生了没有交代的突变（如杯子上一镜在A手中，下一镜在B手中且没有递接动作）。

【定级标准】
- high：矛盾明显，观众一定会出戏（如人还在室内站起，下一镜已在开车）。
- medium：细心观众能察觉的矛盾。
- low：小瑕疵或存在歧义。

【输出要求】
- 只报告有明确矛盾的问题，拿不准的不要报。
- type 只能填：动作衔接 / 服装连续性 / 道具连续性。
- suggested_prompt 给出该镜头可以直接替换使用的中文修正 prompt（保持原有景别与机位风格）。
- 只输出 JSON，不要解释，不要 markdown 代码块：
{
  "issues": [
    {
      "type": "动作衔接",
      "severity": "high",
      "shots": [3, 4],
      "problem": "镜头3结束时……，镜头4开始时……，动作/空间无法衔接",
      "suggestion": "应该补什么镜头或怎么调整",
      "suggested_prompt": "修正后的视频 prompt"
    }
  ]
}
没有问题时输出 {"issues": []}。"""


# ============================================================
# ④ 请求拼装
# ============================================================
def build_shot_user(kind: str, text: str | None) -> str:
    text = (text or "").strip()
    if kind == "image":
        head = "这是某一个镜头的分镜故事板画面，请识别机位、景别、人物站位、人物朝向、服装与动作。"
        if text:
            head += f"\n创作者对该画面的补充说明：{text}"
    else:
        head = f"下面是某一个镜头的视频生成 prompt，请从中解析机位、景别、人物站位、人物朝向、服装与动作：\n\n{text}"
    return f"{head}\n\n{SHOT_OUTPUT_SPEC}"


def build_continuity_user(shot_lines: list[str]) -> str:
    return "镜头序列：\n\n" + "\n\n".join(shot_lines)
